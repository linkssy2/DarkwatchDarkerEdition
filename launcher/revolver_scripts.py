SCRIPT_PATHS = tuple(_PATCHES)


def patch_script(path: str, raw: bytes) -> bytes:
    """Patch an exact original resource, rejecting unsupported input."""
    key = path.replace("\\", "/").lower()
    spec = _PATCHES.get(key)
    if spec is None:
        return raw
    original_hash, patched_hash, splices = spec
    digest = hashlib.sha256(raw).hexdigest()
    if digest == patched_hash:
        return raw
    if digest != original_hash:
        raise ValueError(f"Unsupported starting-revolver script: {key}")
    result = bytearray(raw)
    for offset, removed, added in reversed(splices):
        result[offset:offset + removed] = bytes.fromhex(added)
    if hashlib.sha256(result).hexdigest() != patched_hash:
        raise ValueError(f"Starting-revolver script patch failed: {key}")
    return bytes(result)


def patch_scripts(read: Callable[[str], bytes]) -> dict[str, bytes]:
    return {path: patch_script(path, read(path)) for path in SCRIPT_PATHS}
